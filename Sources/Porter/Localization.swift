import Foundation

/// Translates a user-facing string. The key is the English text (with `%@` / `%ld` placeholders);
/// languages without a translation fall back to it.
func tr(_ key: String, _ args: CVarArg...) -> String {
    let text = Localization.table[Localization.language]?[key] ?? key
    return args.isEmpty ? text : String(format: text, locale: Locale.current, arguments: args)
}

