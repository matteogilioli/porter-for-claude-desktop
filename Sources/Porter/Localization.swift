    static let language: String = {
        let preferred = (UserDefaults.standard.string(forKey: "language").map { [$0] } ?? []) + Locale.preferredLanguages
        for id in preferred {
            if id.hasPrefix("zh-Hans") || id == "zh-CN" || id == "zh" { return "zh-Hans" }
            if id.hasPrefix("zh") { continue }
            if id.hasPrefix("pt") { return "pt-BR" }
            let code = String(id.prefix(2))
            if supported.contains(code) { return code }
        }
        return "en"
    }()

